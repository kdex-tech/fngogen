#!/bin/sh

set -e

# Floor for github.com/kdex-tech/entitlements/go. The generated code imports it
# (NewEntitlementsChecker, ParseRequirements, BindRequirements, ...) and the
# FAT-only security model relies on v0.7.0's parsing, so a module resolving
# anything older is raised to this version. Never lowered: a newer pin wins.
# The above-floor branch can't be exercised against a real module until a
# release newer than v0.7.0 exists; entitlements_needs_raise is unit tested.
ENTITLEMENTS_MIN_VERSION=v0.7.0
ENTITLEMENTS_MODULE=github.com/kdex-tech/entitlements/go

# entitlements_needs_raise <current> <floor>: exit 0 when current must be raised.
# Compares the core version only: `sort -V` (GNU and busybox) ranks v0.7.0-rc.1
# and pseudo-versions ABOVE v0.7.0, whereas semver ranks them below, so a
# pre-release of the floor itself must also be raised.
entitlements_needs_raise() {
  _cur="$1"
  _floor="$2"
  _core="${_cur%%-*}"
  [ "${_core}" = "${_floor}" ] && [ "${_cur}" != "${_core}" ] && return 0
  [ "${_core}" != "${_floor}" ] &&
    [ "$(printf '%s\n%s\n' "${_floor}" "${_core}" | sort -V | head -n1)" != "${_floor}" ] && return 0
  return 1
}

# Tests source this file to reach the functions above without the pipeline.
[ -n "${ENTRY_POINT_FUNCTIONS_ONLY}" ] && return 0

cd "${WORKDIR}"
source .env

cd "${TARGET_DIR}"

# API_IMPORT_PATH (kdex-tech/fngogen#11) places the head inside an existing
# module: it names that module's import path for TARGET_DIR/api, so no nested
# `module function` is created.
[ -z "${API_IMPORT_PATH}" ] && [ ! -f "go.mod" ] && go mod init function

echo "${FUNCTION_API_SPEC}" > openapi-spec.json

# Route text/event-stream responses to ogen's RawHandler (kdex-tech/fngogen#9),
# and rewrite every security alternative to bearer-only, so the function
# accepts only the host-minted FAT (kdex-tech/fngogen#18).
fngogen --prepare --spec openapi-spec.json

cat <<EOF > generate.go
package project

//go:generate go run github.com/ogen-go/ogen/cmd/ogen@latest --target api --clean openapi-spec.json
EOF

go generate ./...

fngogen --spec openapi-spec.json ${API_IMPORT_PATH:+-api-import "$API_IMPORT_PATH"}

go mod tidy

# Raise entitlements/go to the floor when the module resolves a lower version.
# The version that resolves is the replacement's when a replace directive
# applies. A replacement by a local directory has no version: it builds
# whatever that directory holds, and `go get` would only move the require line
# the replace overrides, so it is left alone with a warning, as is an empty
# version. A module that isn't required at all (no security in the spec) is
# skipped; any other failure of `go list` is surfaced. Only stdout is the
# version: a stray stderr line mixed into it would fail the comparison and
# trigger a `go get`, which above the floor is a downgrade. stderr is kept apart
# to classify the failure, and passed through otherwise.
list_err="$(mktemp)"
if listing="$(go list -m -f '{{if .Replace}}{{.Replace.Version}}{{else}}{{.Version}}{{end}}' "${ENTITLEMENTS_MODULE}" 2>"${list_err}")"; then
  cat "${list_err}" >&2
  if [ -z "${listing}" ]; then
    echo "entry-point: warning: ${ENTITLEMENTS_MODULE} resolves to a local directory or no version; not raising ${ENTITLEMENTS_MODULE} to ${ENTITLEMENTS_MIN_VERSION}" >&2
  elif entitlements_needs_raise "${listing}" "${ENTITLEMENTS_MIN_VERSION}"; then
    go get "${ENTITLEMENTS_MODULE}@${ENTITLEMENTS_MIN_VERSION}"
    go mod tidy
  fi
else
  list_stderr="$(cat "${list_err}")"
  case "${list_stderr}" in
    *"not a known dependency"*) ;;
    *) echo "entry-point: go list ${ENTITLEMENTS_MODULE} failed: ${list_stderr}" >&2 ;;
  esac
fi
rm -f "${list_err}"

go vet ./... 2>&1 | grep -v "generated by" || true
go fmt ./...

cat <<EOF > project.toml
[_]
schema-version = "0.2"

[[io.buildpacks.build.env]]
name = "BP_GO_TARGETS"
value = "./cmd/"
EOF

tree .