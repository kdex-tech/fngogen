// BuildOneOff builds the resolved one-off OpenAPI 3.0 document for a single
// KDexFunction, exactly as host-manager does before it hands FUNCTION_API_SPEC
// to the in-cluster codegen Job. It is a faithful port of host-manager's
// internal/openapi buildOpenAPI(isOneOff=true) + FromKDexAPI + toOpenAPIPath +
// the host's SecuritySchemes() registry, kept byte-for-byte compatible by
// reusing the SAME kin-openapi library and marshaling the result with
// json.MarshalIndent(doc, "", "  ") (see writeOneOffSpec). Running it locally
// removes the host-manager dependency that previously forced a cluster
// round-trip to obtain openapi-spec.json. See kdex-tech/fngogen#2.
//
// Assumption: the standard (auth-enabled) security-scheme registry is always
// in scope, matching a host with spec.auth set — the normal case. The one-off
// doc still only carries the schemes an operation actually references (with a
// non-empty scope), identical to host-manager's isOneOff filter.
func BuildOneOff(serverURL string, fn *kdexv1alpha1.KDexFunction) *openapi.T {
	api := &fn.Spec.API

	doc := &openapi.T{
		Components: &openapi.Components{
			Schemas: openapi.Schemas{},
		},
		Info: &openapi.Info{
			Description: "Auto-generated OpenAPI specification for KDex Host",
			Title:       fmt.Sprintf("KDex Host - %s", fn.Name),
			Version:     "1.0.0",
		},
		OpenAPI: "3.0.0",
		Paths:   &openapi.Paths{},
		Servers: openapi.Servers{
			&openapi.Server{URL: serverURL},
		},
	}

	tags := openapi.Tags{}
	securitySchemesUsed := map[string][]string{}

	// A one-off doc describes a single function, so there is exactly one path
	// group (its basePath) and PathInfo.Metadata is the zero value — no
	// per-path metadata tags, AutoGenerated=false. x-kdex-metadata therefore
	// marshals as {"contact":{}} (Tags omitempty, Contact a value struct).
	for curPatternPath, curItem := range api.Paths {
		openapiPath := toOpenAPIPath(curPatternPath)
		if openapiPath == "" {
			continue
		}

		parameters := openapi.Parameters{}
		for _, p := range curItem.GetParameters() {
			parameters = append(parameters, &openapi.ParameterRef{Value: &p})
		}

		pathItem := &openapi.PathItem{
			Description: curItem.Description,
			Extensions: map[string]any{
				// host-manager tags function path items FUNCTION (its
				// internal openapi.FunctionPathType); a one-off doc only ever
				// describes a function, so the value is constant here.
				"x-kdex-type":     "FUNCTION",
				"x-kdex-metadata": kdexv1alpha1.Metadata{},
			},
			Parameters: parameters,
			Summary:    curItem.Summary,
		}

		collectAndSetOpMetadata := func(op *openapi.Operation) {
			if op == nil {
				return
			}
			if op.Summary == "" {
				op.Summary = curItem.Summary
			}
			if op.Description == "" {
				op.Description = curItem.Description
			}
			for _, t := range op.Tags {
				if tags.Get(t) == nil {
					tags = append(tags, &openapi.Tag{Name: t})
				}
			}
			if op.Security != nil {
				for _, scheme := range *op.Security {
					for schemeName, scopes := range scheme {
						for _, scope := range scopes {
							if !slices.Contains(securitySchemesUsed[schemeName], scope) {
								securitySchemesUsed[schemeName] = append(securitySchemesUsed[schemeName], scope)
							}
						}
					}
				}
			}
		}

		if op := curItem.GetGet(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Get = op
		}
		if op := curItem.GetPut(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Put = op
		}
		if op := curItem.GetPost(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Post = op
		}
		if op := curItem.GetDelete(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Delete = op
		}
		if op := curItem.GetOptions(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Options = op
		}
		if op := curItem.GetHead(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Head = op
		}
		if op := curItem.GetPatch(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Patch = op
		}
		if op := curItem.GetTrace(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Trace = op
		}
		if op := curItem.GetConnect(); op != nil {
			collectAndSetOpMetadata(op)
			pathItem.Connect = op
		}

		doc.Paths.Set(openapiPath, pathItem)
	}

	for key, schema := range api.GetSchemas() {
		if _, found := doc.Components.Schemas[key]; found {
			key = key + ":conflict:" + rand.Text()[0:4]
		}
		doc.Components.Schemas[key] = schema
	}

	doc.Tags = tags

	doc.Components.Responses = openapi.ResponseBodies{
		"BadRequest":          &openapi.ResponseRef{Value: &openapi.Response{Description: ptr("Bad Request")}},
		"Found":               &openapi.ResponseRef{Value: &openapi.Response{Description: ptr("Found")}},
		"InternalServerError": &openapi.ResponseRef{Value: &openapi.Response{Description: ptr("Internal Server Error")}},
		"NotFound":            &openapi.ResponseRef{Value: &openapi.Response{Description: ptr("Not Found")}},
		"SeeOther":            &openapi.ResponseRef{Value: &openapi.Response{Description: ptr("See Other")}},
	}

	// Standard scheme registry always in scope; the one-off doc carries only
	// the schemes an operation actually referenced (host-manager's isOneOff
	// branch), and never emits a top-level security requirement.
	schemes := securitySchemes()
	usedSchemes := openapi.SecuritySchemes{}
	for name, scheme := range schemes {
		if scheme.Ref != "" {
			continue
		}
		if _, ok := securitySchemesUsed[name]; ok {
			usedSchemes[name] = scheme
		}
	}
	doc.Components.SecuritySchemes = usedSchemes
	doc.Security = openapi.SecurityRequirements{}

	if len(doc.Components.SecuritySchemes) > 0 {
		doc.Components.Responses["Unauthorized"] = &openapi.ResponseRef{
			Value: &openapi.Response{Description: ptr("Unauthorized")},
		}
	}

	return doc
}

var wildcardRegex = regexp.MustCompile(`\.\.\.\}`)

// toOpenAPIPath converts a net/http route pattern into an OpenAPI path: it
// collapses wildcard captures ({path...} -> {path}), drops the {$} end anchor,
// and trims a trailing slash (except for the bare root). Ported verbatim from
// host-manager internal/openapi.toOpenAPIPath.
func toOpenAPIPath(routePath string) string {
	routePath = strings.ReplaceAll(wildcardRegex.ReplaceAllString(routePath, "}"), "{$}", "")
	if routePath == "/" {
		return routePath
	}
	return strings.TrimSuffix(routePath, "/")
}

// securitySchemes is the KDex host's standard security-scheme registry, ported
// from host-manager internal/host HostHandler.SecuritySchemes() (auth-enabled
// branch). A one-off doc only surfaces the entries an operation references.
func securitySchemes() openapi.SecuritySchemes {
	return openapi.SecuritySchemes{
		"apiKeyCookie": &openapi.SecuritySchemeRef{Value: &openapi.SecurityScheme{
			Description: "Stateless API Token in 'X-API-TOKEN' cookie",
			Type:        "apiKey",
			In:          "cookie",
			Name:        "X-API-TOKEN",
		}},
		"apiKeyHeader": &openapi.SecuritySchemeRef{Value: &openapi.SecurityScheme{
			Description: "Stateless API Token in 'X-API-TOKEN' header",
			Type:        "apiKey",
			In:          "header",
			Name:        "X-API-TOKEN",
		}},
		"apiKeyQuery": &openapi.SecuritySchemeRef{Value: &openapi.SecurityScheme{
			Description: "Stateless API Token in 'api_token' query parameter",
			Type:        "apiKey",
			In:          "query",
			Name:        "api_token",
		}},
		"bearer": &openapi.SecuritySchemeRef{Value: &openapi.SecurityScheme{
			Description:  "Bearer Token - This is the default scheme",
			Type:         "http",
			Scheme:       "bearer",
			BearerFormat: "JWT",
		}},
		"oauth2": &openapi.SecuritySchemeRef{Value: &openapi.SecurityScheme{
			Description: "OAuth2 authentication using Password, Authorization Code, or Client Credentials Flow",
			Flows: &openapi.OAuthFlows{
				AuthorizationCode: &openapi.OAuthFlow{
					AuthorizationURL: "/-/oauth/authorize",
					Scopes: map[string]string{
						"openid":  "standard oidc scope",
						"profile": "user profile info",
					},
					TokenURL: "/-/token",
				},
				ClientCredentials: &openapi.OAuthFlow{
					Scopes: map[string]string{
						"openid":  "standard oidc scope",
						"profile": "user profile info",
					},
					TokenURL: "/-/token",
				},
				Password: &openapi.OAuthFlow{
					Scopes: map[string]string{
						"openid":  "standard oidc scope",
						"profile": "user profile info",
					},
					TokenURL: "/-/token",
				},
			},
			Type: "oauth2",
		}},
		"oidc": &openapi.SecuritySchemeRef{Value: &openapi.SecurityScheme{
			Description:      "OpenID Connect discovery",
			OpenIdConnectUrl: "/.well-known/openid-configuration",
			Type:             "openIdConnect",
		}},
	}
}

func ptr[T any](v T) *T { return &v }
